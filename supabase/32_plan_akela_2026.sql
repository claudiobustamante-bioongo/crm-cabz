-- proponer el año siguiente: promedio del año completo o de los últimos N meses con datos
create or replace function proponer_plan_akela(p_de int, p_a int, p_meses int default null) returns int
language plpgsql security invoker set search_path = public as $$
declare n int; v_desde int := 1; v_hasta int := 12;
begin
  if p_meses is not null then
    select max(mes) into v_hasta from plan_akela where user_id = auth.uid() and anio = p_de and monto > 0;
    v_hasta := coalesce(v_hasta, 12); v_desde := greatest(1, v_hasta - p_meses + 1);
  end if;
  insert into plan_akela (user_id, anio, linea, rubro_id, pagador_id, es_transferencia, mes, monto)
  select auth.uid(), p_a, x.linea, x.rubro_id, x.pagador_id, x.es_transferencia, g.mes, round(x.prom, 2)
  from (select linea, rubro_id, pagador_id, es_transferencia, sum(monto) / (v_hasta - v_desde + 1) as prom
        from plan_akela where user_id = auth.uid() and anio = p_de and mes between v_desde and v_hasta
        group by 1, 2, 3, 4) x
  cross join generate_series(1, 12) as g(mes)
  on conflict (user_id, anio, linea, mes) do nothing;
  get diagnostics n = row_count; return n;
end $$;
grant execute on function proponer_plan_akela(int, int, int) to authenticated;

