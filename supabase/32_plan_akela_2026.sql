-- 2027: líneas recurrentes (con gasto en 9+ meses de 2026) = mediana de ago–oct 2026 (los últimos 3 meses reales);
--       líneas anuales o irregulares (seguros, predial, tenencia, viajes…) = total 2026 / 12. Editable en la pestaña.
insert into plan_akela (anio, linea, rubro_id, pagador_id, es_transferencia, mes, monto)
select 2027, x.linea, x.rubro_id, x.pagador_id, x.es_transferencia, g.mes,
       round((case when x.meses_con_gasto >= 9 then x.mediana_ult3 else x.total / 12 end)::numeric, 0)
from (
  select linea, rubro_id, pagador_id, es_transferencia,
         count(*) filter (where monto > 0) as meses_con_gasto,
         sum(monto) as total,
         percentile_cont(0.5) within group (order by monto) filter (where mes between 8 and 10) as mediana_ult3
  from plan_akela where user_id = crm_owner() and anio = 2026
  group by linea, rubro_id, pagador_id, es_transferencia) x
cross join generate_series(1, 12) as g(mes);

select anio, count(distinct linea) as lineas, sum(monto) as total from plan_akela where anio in (2026, 2027) group by 1 order by 1;
select linea, sum(monto) as plan_2027 from plan_akela where anio = 2027 group by 1 order by 2 desc;
